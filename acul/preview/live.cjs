const { chromium } = require("playwright")
const out = process.argv[2]
;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 })
  const errs = []
  page.on("pageerror", (e) => errs.push("pageerror: " + e.message))
  page.on("console", (m) => m.type() === "error" && errs.push("console: " + m.text()))
  await page.goto("https://kinetik-store-zeta.vercel.app/account", { waitUntil: "networkidle" })
  await page.getByRole("button", { name: /sign in/i }).first().click()
  await page.waitForURL(/mmatias\.co\.uk/, { timeout: 30000 })
  await page.waitForSelector(".k-card", { timeout: 30000 })
  console.log("login-id url:", page.url().split("?")[0])
  await page.screenshot({ path: `${out}/live-1-login-id.png` })
  await page.fill("#k-username", "kinetik-ui-check@example.com")
  await page.click("button[type=submit]")
  await page.waitForSelector("#k-password", { timeout: 30000 })
  console.log("password url:", page.url().split("?")[0])
  await page.fill("#k-password", "definitely-wrong-1")
  await page.click("button[type=submit]")
  await page.waitForSelector(".k-alert, .k-field-error", { timeout: 30000 })
  console.log("error shown:", (await page.locator(".k-alert, .k-field-error").first().innerText()).trim())
  await page.screenshot({ path: `${out}/live-2-password-error.png` })
  const signup = page.locator("a", { hasText: "Edit" })
  await signup.click()
  await page.waitForSelector("#k-username")
  await page.locator("a", { hasText: "Join us" }).click()
  await page.waitForSelector("#k-email", { timeout: 30000 })
  await page.screenshot({ path: `${out}/live-3-signup.png` })
  console.log("signup url:", page.url().split("?")[0])
  await browser.close()
  console.log(errs.length ? errs.join("\n") : "no page errors")
})().catch((e) => { console.error("FAILED:", e.message); process.exit(1) })
